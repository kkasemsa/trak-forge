// Builds js/data/presets.js from seqtrak-docs' data/presets.csv (the transcribed Yamaha preset list).
//   node scripts/make-presets.mjs path/to/seqtrak-docs/data/presets.csv
// Only the bank-63 catalogue (Drum, Synth, DX) is kept: it is the one CurrentSound indexes.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/make-presets.mjs <presets.csv>'); process.exit(1); }
const rows = readFileSync(src, 'utf8').trim().split('\n').slice(1).map(line => {
  const [engine, number, ...rest] = line.split(',');
  const program = rest.pop(); const bankLsb = rest.pop(); const bankMsb = rest.pop(); const category = rest.pop();
  return { engine, number: Number(number), name: rest.join(','), category, bankMsb: Number(bankMsb), bankLsb: Number(bankLsb), program: Number(program) };
}).filter(r => r.bankMsb === 63).sort((a, b) => a.number - b.number);

rows.forEach((r, i) => { if (r.number !== i + 1) throw new Error(`gap in catalogue at ${r.number}`); });
const out = join(dirname(fileURLToPath(import.meta.url)), '../js/data/presets.js');
const body = rows.map(r => JSON.stringify([r.name, r.category, r.engine])).join(',\n');
writeFileSync(out, `// Generated by scripts/make-presets.mjs from jaeggerr/seqtrak-docs data/presets.csv. Do not edit.\n// Index = catalogue number - 1. Entry = [name, category, engine].\nexport const PRESETS = [\n${body}\n];\n`);
console.log(`${rows.length} presets written`);
